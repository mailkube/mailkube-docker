#  Listener TLS
# --------------------------------------------------------------------------- #
def test_t30_tls_makes_auth_conditional_on_starttls(factory, listener_certs):
    sink = factory.sink()
    relay = factory.relay(
        RELAY_AUTH_USERS=f"{USER}:{SECRET}",
        RELAY_AUTH_REQUIRED="yes",
        RELAY_TLS_CERT_FILE="/tls/tls.crt",
        RELAY_TLS_KEY_FILE="/tls/tls.key",
        extra_args=["-v", f"{listener_certs}:/tls:ro"],
    )
    assert relay.postconf_one("smtpd_tls_security_level") == "encrypt"
    assert relay.postconf_one("smtpd_tls_auth_only") == "yes"

    # Credentials must not be accepted before the channel is encrypted.
    assert _auth_probe(relay, USER, SECRET) == "530"

    # ... and must work after STARTTLS.
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    with smtplib.SMTP("127.0.0.1", relay.port, timeout=20) as s:
        s.starttls(context=ctx)
        s.login(USER, SECRET)
        s.send_message(message(subject="authenticated over TLS"))

    assert len(sink.wait_for_messages(1)) == 1


def test_t30b_healthcheck_survives_mandatory_tls(factory, listener_certs):
    """`encrypt` refuses mail commands before STARTTLS, but the banner and QUIT
    are still allowed, which is all the probe uses. If this regresses, every
    deployment with listener TLS flaps."""
    factory.sink()
    relay = factory.relay(
        RELAY_TLS_CERT_FILE="/tls/tls.crt",
        RELAY_TLS_KEY_FILE="/tls/tls.key",
        extra_args=["-v", f"{listener_certs}:/tls:ro"],
    )
    assert relay.exec("/usr/local/bin/healthcheck.sh", check=False).returncode == 0


