def test_t31_required_without_accounts_is_refused(factory):
    """Otherwise every client, including the healthcheck, would be rejected."""
    p = factory.run_to_completion(
        SMTP_USERNAME=f"myapp01@{AUTH_DOMAIN}", SMTP_PASSWORD="x", RELAY_AUTH_REQUIRED="yes"
    )
    assert p.returncode != 0
    assert "no accounts are configured" in (p.stdout + p.stderr)


def test_t31b_malformed_account_list_is_refused(factory):
    p = factory.run_to_completion(
        SMTP_USERNAME=f"myapp01@{AUTH_DOMAIN}", SMTP_PASSWORD="x", RELAY_AUTH_USERS="nopasswordhere"
    )
    assert p.returncode != 0
    assert "user:password" in (p.stdout + p.stderr)


