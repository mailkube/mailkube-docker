"""T-25..T-31: optional inbound authentication and listener TLS.

The relay is unauthenticated by default. These cover the opt-in mode that lets an
operator narrow `mynetworks` and require credentials from every client, which is
the only in-container defence against a compromised pod in the same namespace.
"""

from __future__ import annotations

import smtplib
import ssl
import subprocess
import time

import pytest

from conftest import AUTH_DOMAIN, docker, message

USER = "app1"
SECRET = "hunter2xyzverysecret"


@pytest.fixture
def listener_certs(tmp_path):
    """A self-signed certificate for the relay's own listener.

    Deliberately generated by the TEST, not by the image. The image only ever
    mounts a certificate: generating one at startup would force every client to
    disable verification, which teaches people to accept any certificate.
    """
    out = tmp_path / "listener"
    out.mkdir()
    docker(
        "run", "--rm", "-v", f"{out}:/out", "alpine:3.24", "sh", "-c",
        "apk add --no-cache -q openssl && openssl req -x509 -newkey rsa:2048 -nodes -days 3650 "
        "-subj '/CN=mailkube-relay' -keyout /out/tls.key -out /out/tls.crt && chmod 644 /out/tls.*",
    )
    return out


def _auth_probe(relay, user: str, password: str) -> str:
    """Run an AUTH PLAIN exchange inside the container and return the reply code."""
    script = (
        f'A=$(printf "\\0{user}\\0{password}" | base64 | tr -d "\\n"); '
        '(sleep 0.4; printf "EHLO t\\r\\n"; sleep 0.4; '
        'printf "AUTH PLAIN %s\\r\\n" "$A"; sleep 0.6; printf "QUIT\\r\\n") '
        f'| nc -w 5 127.0.0.1 {relay_port(relay)}'
    )
    out = relay.exec("sh", "-c", script, check=False).stdout
    for line in out.replace("\r", "").splitlines():
        if line[:3] in {"235", "535", "530", "538", "503"}:
            return line[:3]
    return "???"


def relay_port(relay) -> str:
    return "25"


