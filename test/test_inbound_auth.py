def test_t26_accounts_enable_sasl_and_accept_the_right_password(factory):
    factory.sink()
    relay = factory.relay(RELAY_AUTH_USERS=f"{USER}:{SECRET}")

    assert relay.postconf_one("smtpd_sasl_auth_enable") == "yes"
    assert "permit_sasl_authenticated" in relay.postconf_one("smtpd_client_restrictions")
    assert _auth_probe(relay, USER, SECRET) == "235"


