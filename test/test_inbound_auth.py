def test_t29_required_auth_rejects_an_unauthenticated_sender(factory):
    """A client on the docker bridge is inside the default mynetworks.

    With RELAY_AUTH_REQUIRED=yes, permit_mynetworks is dropped, so being on a
    private network is no longer enough.
    """
    factory.sink()
    relay = factory.relay(RELAY_AUTH_USERS=f"{USER}:{SECRET}", RELAY_AUTH_REQUIRED="yes")
    assert relay.postconf_one("smtpd_client_restrictions") == (
        "permit_inet_interfaces, permit_sasl_authenticated, reject"
    )

    with pytest.raises(smtplib.SMTPException):
        relay.send(message(subject="should be refused"))


def test_t29b_required_auth_accepts_an_authenticated_sender(factory):
    sink = factory.sink()
    relay = factory.relay(RELAY_AUTH_USERS=f"{USER}:{SECRET}", RELAY_AUTH_REQUIRED="yes")

    with smtplib.SMTP("127.0.0.1", relay.port, timeout=20) as s:
        s.login(USER, SECRET)
        s.send_message(message(subject="authenticated send"))

    msgs = sink.wait_for_messages(1)
    assert len(msgs) == 1, "an authenticated client must be able to send"


